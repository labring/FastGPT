import z from 'zod';
import { BoolSchema } from '@fastgpt/global/common/zod';
import type { ChatOperation } from '../../domain/chat/chat-service';
import { CliArgumentError } from '../../shared/errors';
import type { CommandOptionMeta } from '../../shared/types';
import type { CliCommandSpec } from '../pipeline';

type ChatOption = CommandOptionMeta & { encoding?: 'json' | 'csv' | 'boolean' };

/** 注册 App 会话的十个 OpenAPI 命令；帮助、参数清单与实际请求共用同一份声明。 */
export function createChatCommandSpecs(): CliCommandSpec[] {
  function value({
    name,
    description,
    encoding
  }: Pick<ChatOption, 'name' | 'description' | 'encoding'>): ChatOption {
    return {
      name,
      flags: `--${name} <${encoding ?? 'value'}>`,
      takesValue: true,
      description,
      encoding
    };
  }
  function flag(name: string, description: string): ChatOption {
    return { name, flags: `--${name}`, takesValue: false, description };
  }

  const targetOptions = [
    value({ name: 'appId', description: 'Target App ID; optional for an App API Key' }),
    value({
      name: 'customUid',
      description: 'App conversation user ID (API Keys only; mutually exclusive with authProxy)'
    }),
    value({
      name: 'authProxy',
      description:
        'Proxy App access as {"tmbId":"..."} or {"username":"..."} using an enabled personal API Key',
      encoding: 'json'
    })
  ];
  const chatId = value({ name: 'chatId', description: 'App conversation ID' });
  const dryRun = {
    ...flag('dryRun', 'Validate and preview the request without making changes'),
    flags: '--dry-run'
  };
  const definitions: {
    operation: ChatOperation;
    summary: string;
    risk: CliCommandSpec['risk'];
    options: ChatOption[];
    example: string[];
  }[] = [
    {
      operation: 'run',
      summary: 'Run an App conversation and return its JSON response',
      risk: 'write',
      options: [
        value({ name: 'text', description: 'User question; mutually exclusive with messages' }),
        value({ name: 'messages', description: 'OpenAI-format message array', encoding: 'json' }),
        { ...chatId, description: 'App conversation ID; omit to create a new conversation' },
        value({ name: 'variables', description: 'App variables', encoding: 'json' }),
        value({ name: 'metadata', description: 'App conversation metadata', encoding: 'json' }),
        value({
          name: 'responseChatItemId',
          description: 'Custom assistant message ID; generated by default'
        }),
        flag('detail', 'Include detailed App response data and updated variables (default false)'),
        flag('retainDatasetCite', 'Keep dataset citations in the App response (default false)'),
        flag('showSkillReferences', 'Include references in the App response (default false)'),
        value({
          name: 'file',
          description: 'Read a JSON request object from a file (- reads stdin)'
        }),
        flag('stdin', 'Read a JSON request object from stdin'),
        value({
          name: 'timeoutMs',
          description:
            'HTTP timeout in milliseconds (default 300000); a timeout does not stop the App'
        }),
        dryRun
      ],
      example: ['--text', 'Hello']
    },
    {
      operation: 'stop',
      summary: 'Send an App conversation stop signal without waiting for workflow cleanup',
      risk: 'write',
      options: [chatId, dryRun],
      example: ['--chatId', 'conversation-id']
    },
    {
      operation: 'init',
      summary:
        'Read App configuration, variables, and conversation status without creating a conversation',
      risk: 'read',
      options: [chatId],
      example: ['--chatId', 'conversation-id']
    },
    {
      operation: 'history list',
      summary: 'List accessible App conversations with pagination and filters',
      risk: 'read',
      options: [
        value({ name: 'pageNum', description: 'Page number, starting at 1 (default 1)' }),
        value({ name: 'pageSize', description: 'Items per page (default 20, capped at 500)' }),
        value({ name: 'offset', description: 'Zero-based offset; takes precedence over pageNum' }),
        value({
          name: 'source',
          description: 'App entry source, e.g. api, online, test; App API Keys always use api'
        }),
        ...['startCreateTime', 'endCreateTime', 'startUpdateTime', 'endUpdateTime'].map((name) =>
          value({ name: name, description: `App conversation time filter: ${name}` })
        )
      ],
      example: ['--pageSize', '20']
    },
    {
      operation: 'history status',
      summary: 'Read generation and read status for App conversations',
      risk: 'read',
      options: [
        value({
          name: 'chatIds',
          description: 'Comma-separated App conversation IDs (1 to 200)',
          encoding: 'csv'
        })
      ],
      example: ['--chatIds', 'conversation-1,conversation-2']
    },
    {
      operation: 'history mark-read',
      summary: 'Mark an App conversation as read',
      risk: 'write',
      options: [chatId, dryRun],
      example: ['--chatId', 'conversation-id']
    },
    {
      operation: 'history update',
      summary: 'Update an App conversation title or pinned state',
      risk: 'write',
      options: [
        chatId,
        value({ name: 'title', description: 'App conversation title' }),
        value({ name: 'customTitle', description: 'Custom title (an empty string clears it)' }),
        value({
          name: 'top',
          description: 'Pin or unpin the App conversation: true or false',
          encoding: 'boolean'
        }),
        dryRun
      ],
      example: ['--chatId', 'conversation-id', '--top', 'false']
    },
    {
      operation: 'history delete',
      summary: 'Soft-delete an App conversation',
      risk: 'destructive',
      options: [chatId, flag('yes', 'Confirm deletion'), dryRun],
      example: ['--chatId', 'conversation-id', '--yes']
    },
    {
      operation: 'record list',
      summary: 'List App messages with cursor pagination (latest messages by default)',
      risk: 'read',
      options: [
        chatId,
        value({
          name: 'pageSize',
          description:
            'Target messages per page (default 20, capped at 500); full round boundaries may add messages'
        }),
        value({ name: 'prevId', description: 'Load older rounds; pass meta.prevCursor unchanged' }),
        value({ name: 'nextId', description: 'Load newer rounds; pass meta.nextCursor unchanged' }),
        value({
          name: 'initialId',
          description: 'Load messages around this dataId; use only one cursor'
        }),
        flag('includeDeleted', 'Include soft-deleted App messages'),
        flag('loadCustomFeedbacks', 'Include custom App message feedback')
      ],
      example: ['--chatId', 'conversation-id', '--pageSize', '20']
    },
    {
      operation: 'record detail',
      summary: 'Read detailed response data for an App assistant message',
      risk: 'read',
      options: [
        chatId,
        value({ name: 'dataId', description: 'Assistant message data ID (not its database _id)' })
      ],
      example: ['--chatId', 'conversation-id', '--dataId', 'message-id']
    }
  ];

  return definitions.map((definition): CliCommandSpec => {
    const fields = [...targetOptions, ...definition.options];
    return {
      path: ['chat', ...definition.operation.split(' ')],
      summary: definition.summary,
      risk: definition.risk,
      authModes: ['token', 'personalKey', 'appKey'],
      options: fields.map(({ encoding, ...option }) => option),
      examples: [
        {
          description: definition.summary,
          args: [
            'chat',
            ...definition.operation.split(' '),
            '--appId',
            '68ad85a7463006c963799a05',
            ...definition.example
          ]
        }
      ],
      execute: async ({ options, client, container, resolvedAuth }) => {
        if (!client)
          throw new CliArgumentError('Active HTTP client required for App conversations.');

        const input = z.record(z.string(), z.unknown()).parse(
          definition.operation === 'run'
            ? await container.readJsonInput({
                file: options.file as string | undefined,
                stdin: options.stdin === true
              })
            : {}
        );
        const localOptions = ['file', 'stdin', 'timeoutMs', 'dryRun', 'yes', 'text'];
        for (const field of fields) {
          const raw = options[field.name];
          if (raw === undefined || localOptions.includes(field.name)) continue;
          if (input[field.name] !== undefined) {
            throw new CliArgumentError(
              `Provide ${field.name} either in the JSON request or as a flag, not both.`
            );
          }
          input[field.name] = (() => {
            if (field.encoding === 'json') {
              try {
                return JSON.parse(String(raw));
              } catch {
                throw new CliArgumentError(`--${field.name} must be valid JSON.`);
              }
            }
            if (field.encoding === 'csv')
              return String(raw)
                .split(',')
                .map((id) => id.trim());
            if (field.encoding === 'boolean')
              return BoolSchema.parse(z.enum(['true', 'false']).parse(raw));
            return raw;
          })();
        }
        if (options.text !== undefined) {
          if (input.messages !== undefined)
            throw new CliArgumentError('Use either --text or messages.');
          input.messages = [{ role: 'user', content: options.text }];
        }

        if (definition.risk === 'destructive' && options.dryRun !== true && options.yes !== true) {
          const confirmed = await container.prompter.confirm({
            message: `Delete App conversation "${String(input.chatId ?? '')}" in App "${String(input.appId ?? resolvedAuth?.credential?.boundAppId ?? 'bound to the active API Key')}"?`,
            initialValue: false
          });
          if (!confirmed) throw new CliArgumentError('App conversation deletion cancelled.');
        }

        return container.chatService.execute({
          operation: definition.operation,
          client,
          input,
          credential: resolvedAuth?.credential,
          dryRun: options.dryRun === true,
          timeoutMs: options.timeoutMs
        });
      }
    };
  });
}
