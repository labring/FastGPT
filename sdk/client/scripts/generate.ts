import { jsonSchema, renderType } from './schema';
import { readFile, writeFile } from 'node:fs/promises';
import { resolve } from 'node:path';
import { contracts } from './contracts';
import { format, resolveConfig } from 'prettier';
import { SystemOpenApiTagMap } from '@fastgpt/global/openapi/tag';
import { pathToFileURL } from 'node:url';

const datasetSource = process.env.FASTGPT_API_CONTRACTS_ROOT
  ? pathToFileURL(
      resolve(
        process.env.FASTGPT_API_CONTRACTS_ROOT,
        'packages/global/openapi/core/dataset/index.ts'
      )
    ).href
  : '@fastgpt/global/openapi/core/dataset';
const { DatasetPath }: typeof import('@fastgpt/global/openapi/core/dataset') = await import(
  datasetSource
);

const check = process.argv.includes('--check');
const inputs: Record<string, unknown> = {};
const operationLines: string[] = [];
const typeLines: string[] = [];
const publicTags = new Set<string>(Object.values(SystemOpenApiTagMap));
for (const [name, contract] of Object.entries(contracts)) {
  // 与正式 Open API 文档使用相同的显式标签边界，防止把控制台接口带入客户端。
  const operation =
    DatasetPath?.[`/${contract.path}`]?.[
      contract.method.toLowerCase() as Lowercase<typeof contract.method>
    ];
  if (operation?.deprecated || !operation?.tags?.some((tag) => publicTags.has(tag))) {
    throw new Error(`SDK operation must reference an active public Open API: ${name}`);
  }
  const input = jsonSchema(contract.input, 'input');
  inputs[name] = input;
  const output =
    typeof contract.output === 'string'
      ? contract.output === 'download'
        ? 'Response'
        : contract.output
      : renderType(jsonSchema(contract.output, 'output'));
  typeLines.push(`${JSON.stringify(name)}: { input: ${renderType(input)}; output: ${output}; };`);
  const { input: _input, output: _output, ...spec } = contract;
  operationLines.push(
    `${JSON.stringify(name)}: ${JSON.stringify({
      ...spec,
      ...(contract.output === 'download' ? { download: true } : {}),
      ...(contract.output === 'void' ? { empty: true } : {})
    })},`
  );
}

const header =
  '// Generated by scripts/generate.ts from shared API schemas. Do not edit manually.\n';
const files = {
  'type.ts': `${header}export type DatasetOperations = {\n${typeLines.join('\n')}\n};\nexport type DatasetOperation = keyof DatasetOperations;\nexport type DatasetInput<Key extends DatasetOperation> = DatasetOperations[Key]['input'];\nexport type DatasetOutput<Key extends DatasetOperation> = DatasetOperations[Key]['output'];\nexport type Dataset = DatasetOutput<'get'>;\nexport type Collection = DatasetOutput<'collections.get'>;\nexport type Chunk = DatasetOutput<'chunks.get'>;\nexport type CreateDatasetParams = DatasetInput<'create'>;\nexport type SearchParams = DatasetInput<'search'>;\n`,
  'operations.ts': `${header}export const datasetOperations = {\n${operationLines.join('\n')}\n} as const;\n`,
  'schema.ts': `${header}export const datasetInputSchemas: Record<string, object> = ${JSON.stringify(inputs)};\n`
};
for (const [name, content] of Object.entries(files)) {
  const path = resolve(import.meta.dirname, '../src/dataset', name);
  const formatted = await format(content, { ...(await resolveConfig(path)), parser: 'typescript' });
  if (check) {
    if ((await readFile(path, 'utf8')) !== formatted)
      throw new Error(`Generated contract is stale: ${name}`);
  } else await writeFile(path, formatted);
}
console.log(
  `${check ? 'Verified' : 'Generated'} ${Object.keys(contracts).length} typed dataset operations`
);
