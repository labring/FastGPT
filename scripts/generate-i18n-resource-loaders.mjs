import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const i18nDir = path.join(rootDir, 'packages/web/i18n');
const isCheck = process.argv.includes('--check');

// 1. 读取语言与命名空间列表
const readList = (filePath, regex) =>
  Array.from(fs.readFileSync(filePath, 'utf8').match(regex)?.[1].matchAll(/'([^']+)'/g), (m) => m[1]);

const languages = readList(
  path.join(rootDir, 'packages/global/common/i18n/type.ts'),
  /LocaleList\s*=\s*\[([\s\S]*?)\]\s*as const/
);
const namespaces = readList(
  path.join(i18nDir, 'constants.ts'),
  /I18N_NAMESPACES\s*=\s*\[([\s\S]*?)\]/
);

// 2. 校验 JSON 资源完整性
for (const lang of languages) {
  for (const ns of namespaces) {
    if (!fs.existsSync(path.join(i18nDir, lang, `${ns}.json`))) {
      throw new Error(`Missing i18n resource: ${lang}/${ns}`);
    }
  }
}

// 3. 构建待生成文件列表
const files = [];

// 3.1 为每种语言生成静态聚合入口（用于 Webpack 按语言打包为单一独立 Chunk）
for (const lang of languages) {
  const imports = namespaces.map((ns) => `import ${ns} from '../${lang}/${ns}.json';`).join('\n');
  const exports = namespaces.map((ns) => `  ${ns}`).join(',\n');
  files.push({
    filePath: path.join(i18nDir, 'bundles', `${lang}.ts`),
    content: `// This file is generated by scripts/generate-i18n-resource-loaders.mjs.
// Do not edit manually.
${imports}

export default {
${exports}
};
`
  });
}

// 3.2 聚合索引入口 resourceLoaders.generated.ts
const loadersBody = languages
  .map((lang) => {
    const key = lang.includes('-') ? `'${lang}'` : lang;
    const entries = namespaces
      .map((ns) => `    ${ns}: () => import('./${lang}/${ns}.json')`)
      .join(',\n');
    return `  ${key}: {\n${entries}\n  }`;
  })
  .join(',\n');

const bundlesBody = languages
  .map((lang) => {
    const key = lang.includes('-') ? `'${lang}'` : lang;
    return `  ${key}: () => import(/* webpackChunkName: "i18n-${lang}" */ './bundles/${lang}')`;
  })
  .join(',\n');

files.push({
  filePath: path.join(i18nDir, 'resourceLoaders.generated.ts'),
  content: `// This file is generated by scripts/generate-i18n-resource-loaders.mjs.
// Do not edit manually.
import type { I18nNsType } from './i18next';
import type { localeType } from '@fastgpt/global/common/i18n/type';

type LocaleResource = Record<string, string | Record<string, unknown>>;
type ResourceLoader = () => Promise<{ default: LocaleResource }>;
type LanguageBundle = Record<I18nNsType[number], LocaleResource>;
type BundleLoader = () => Promise<{ default: LanguageBundle }>;

export const generatedLoaders: Record<localeType, Record<I18nNsType[number], ResourceLoader>> = {
${loadersBody}
};

export const generatedLanguageBundles: Record<localeType, BundleLoader> = {
${bundlesBody}
};
`
});

// 4. 统一处理写入或校验
for (const { filePath, content } of files) {
  if (isCheck) {
    const current = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : '';
    if (current !== content) {
      throw new Error(
        `i18n resource loader is outdated. Run \`pnpm generate:i18n-loaders\` and commit the result.`
      );
    }
  } else {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, content);
  }
}

console.log(
  isCheck
    ? 'i18n resource loader is up to date.'
    : 'Generated packages/web/i18n/bundles and packages/web/i18n/resourceLoaders.generated.ts'
);
