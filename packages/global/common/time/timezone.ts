import timezones from 'timezones-list';
import dayjs from 'dayjs';
import utc from 'dayjs/plugin/utc.js';
import timezone from 'dayjs/plugin/timezone.js';

// timezones-list is CJS; under ESM interop the default import may receive
// {default: [...]} instead of the array. Normalize at import time.
const tz = (timezones as any)?.default ?? timezones;
if (!Array.isArray(tz)) {
  throw new Error('timezones-list default import failed: expected array');
}

dayjs.extend(utc);
dayjs.extend(timezone);

/**
 * Returns the offset from UTC in hours for the current locale.
 * @param {string} timeZone Timezone to get offset for
 * @returns {number} The offset from UTC in hours.
 *
 * Generated by Trelent
 */
export const getTimezoneOffset = (timeZone: string): number => {
  const now = new Date();
  const tzString = now.toLocaleString('en-US', {
    timeZone
  });
  const localString = now.toLocaleString('en-US');
  const diff = (Date.parse(localString) - Date.parse(tzString)) / 3600000;
  const offset = diff + now.getTimezoneOffset() / 60;
  // Ensure we return +0 instead of -0 for UTC
  return offset === 0 ? 0 : -offset;
};

/**
 * Returns a list of timezones sorted by their offset from UTC.
 * @returns {object[]} A list of the given timezones sorted by their offset from UTC.
 *
 * Generated by Trelent
 */
export const getTimeZoneList = () => {
  const result = tz
    .map((timezone) => {
      try {
        const display = dayjs().tz(timezone.tzCode).format('Z');

        return {
          name: `(UTC${display}) ${timezone.tzCode}`,
          value: timezone.tzCode,
          time: getTimezoneOffset(timezone.tzCode)
        };
      } catch (e) {}
    })
    .filter((item) => item);

  result.sort((a, b) => {
    if (!a || !b) return 0;
    if (a.time > b.time) {
      return 1;
    }

    if (b.time > a.time) {
      return -1;
    }

    return 0;
  });

  return [
    {
      name: 'UTC',
      time: 0,
      value: 'UTC'
    },
    ...result
  ] as {
    name: string;
    value: string;
    time: number;
  }[];
};
export const timeZoneList = getTimeZoneList();

/**
 * 优先使用时间字符串自带的偏移，Z 明确表示 UTC。
 * 无偏移字符串及 Date 使用该时刻的服务器本地偏移；无效值回落到当前服务器偏移，输入合法性由 API 校验。
 * 返回固定偏移，不尝试根据起止时间反推 IANA 时区或中途的 DST 规则。
 */
export const getTimezoneCodeFromStr = (timeString: string | Date) => {
  if (typeof timeString === 'string') {
    const timezoneMatch = timeString.match(/([+-]\d{2}:\d{2})$/);
    if (timezoneMatch) return timezoneMatch[1];
    if (/Z$/i.test(timeString)) return '+00:00';
  }

  const localDate = dayjs(timeString);
  return (localDate.isValid() ? localDate : dayjs()).format('Z');
};

export const getSystemTime = (timeZone: string) => {
  const timezoneDiff = getTimezoneOffset(timeZone);
  const now = Date.now();
  const targetTime = now + timezoneDiff * 60 * 60 * 1000;
  return dayjs(targetTime).format('YYYY-MM-DD HH:mm:ss dddd');
};
